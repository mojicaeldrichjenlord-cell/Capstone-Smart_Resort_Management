/**
 * Real, gated MySQL concurrency integration tests for Front Desk add-ons.
 * Run from backend: node --test tests/frontdesk-mysql-concurrency.integration.test.js
 *
 * DOES NOT LOAD .env, server.js, Aiven config, or PayPal.
 * Only uses a localhost MySQL server with user smartresort_lock_test,
 * and only after explicit opt-in. Creates and drops its own random test
 * DATABASE, never defaultdb, and never a pre-existing database.
 */
const assert = require("node:assert/strict");
const crypto = require("node:crypto");
const Module = require("node:module");
const { test, before, after } = require("node:test");
const mysql = require("mysql2/promise");

const TEST_USER = "smartresort_lock_test";
const schema = process.env.SMARTRESORT_TEST_SCHEMA ||
  "smartresort_concurrency_" + crypto.randomBytes(7).toString("hex");
let adminConnection = null;
let pool = null;
let schemaCreated = false;
let addAccommodation = null;

function options() {
  const host = process.env.SMARTRESORT_TEST_MYSQL_HOST;
  const user = process.env.SMARTRESORT_TEST_MYSQL_USER;
  const password = process.env.SMARTRESORT_TEST_MYSQL_PASSWORD;
  const port = Number(process.env.SMARTRESORT_TEST_MYSQL_PORT || 3306);
  assert.equal(process.env.SMARTRESORT_ALLOW_LOCAL_MYSQL_TEST,
    "LOCAL_DISPOSABLE_MYSQL_ONLY", "Local MySQL test opt-in is required.");
  assert.ok(["127.0.0.1", "localhost", "::1"].includes(host),
    "Only a LOCAL MySQL host is allowed, never Aiven.");
  assert.equal(user, TEST_USER,
    "Use a dedicated smartresort_lock_test account, NOT the application's DB_USER.");
  assert.ok(typeof password === "string" && password.length > 0,
    "Dedicated local test password is required.");
  assert.ok(Number.isInteger(port) && port > 0 && port <= 65535,
    "Invalid local MySQL test port.");
  return { host, port, user, password,
    dateStrings: true, multipleStatements: false, connectTimeout: 5000 };
}

function replaceModule(relativePath, value) {
  const path = require.resolve(relativePath);
  const m = new Module(path);
  m.filename = path;
  m.loaded = true;
  m.exports = value;
  require.cache[path] = m;
}

async function setup() {
  const cfg = options(); // Safety guards run BEFORE any database connection.
  adminConnection = await mysql.createConnection(cfg);
  const [[identity]] = await adminConnection.query(
    "SELECT @@hostname AS host_name, @@version AS server_version, " +
    "@@version_comment AS version_comment, @@port AS server_port, " +
    "CURRENT_USER() AS authenticated_user");
  const signature = String(identity.host_name || "") + " " +
    String(identity.version_comment || "");
  assert.doesNotMatch(signature,
    /aiven|amazon|aurora|planetscale|tidb|cloudsql|render/i,
    "Hosted database fingerprint detected; refusing any schema changes.");
  const expectedHostname = process.env.SMARTRESORT_TEST_EXPECTED_HOSTNAME;
  assert.ok(expectedHostname, "Expected local hostname is required.");
  assert.equal(String(identity.host_name).toLowerCase(), expectedHostname.toLowerCase(),
    "Database server hostname differs from the verified local machine.");
  assert.match(String(identity.server_version), /MariaDB/i,
    "This test is restricted to the verified local XAMPP MariaDB service.");
  assert.equal(Number(identity.server_port), Number(cfg.port));
  assert.match(String(identity.authenticated_user),
    /^smartresort_lock_test@127\.0\.0\.1$/i,
    "Database login is not the dedicated localhost-only test user.");

  // The random schema is generated by this test and cannot name defaultdb.
  assert.match(schema, /^smartresort_concurrency_[a-f0-9]{14}$/);
  await adminConnection.query("CREATE DATABASE " + schema);
  schemaCreated = true;
  pool = mysql.createPool({ ...cfg, database: schema,
    waitForConnections: true, connectionLimit: 8, queueLimit: 0 });

  const ddl = [
    "CREATE TABLE accommodation_categories (" +
    "id INT PRIMARY KEY, name VARCHAR(80) NOT NULL) ENGINE=InnoDB",
    "CREATE TABLE accommodations (" +
    "id INT PRIMARY KEY, category_id INT NOT NULL, name VARCHAR(80) NOT NULL," +
    "description TEXT NULL, max_capacity INT DEFAULT 10," +
    "free_entrance_pax INT DEFAULT 0, image VARCHAR(250) NULL," +
    "map_label VARCHAR(100) NULL, status VARCHAR(40) NOT NULL," +
    "day_price DECIMAL(12,2) NOT NULL, overnight_price DECIMAL(12,2) NOT NULL," +
    "extended_price DECIMAL(12,2) NOT NULL," +
    "day_start_time TIME NULL, day_end_time TIME NULL," +
    "overnight_start_time TIME NULL, overnight_end_time TIME NULL," +
    "extended_start_time TIME NULL, extended_end_time TIME NULL) ENGINE=InnoDB",
    "CREATE TABLE reservations (" +
    "id INT PRIMARY KEY, reservation_code VARCHAR(50) NOT NULL," +
    "reservation_status VARCHAR(30) NOT NULL, payment_status VARCHAR(30) NOT NULL," +
    "is_checked_in TINYINT NOT NULL, accommodation_total DECIMAL(12,2) NOT NULL," +
    "required_downpayment DECIMAL(12,2) NOT NULL," +
    "paid_amount DECIMAL(12,2) NOT NULL, remaining_balance DECIMAL(12,2) NOT NULL," +
    "note TEXT NULL) ENGINE=InnoDB",
    "CREATE TABLE reservation_items (" +
    "id INT AUTO_INCREMENT PRIMARY KEY, reservation_id INT NOT NULL," +
    "accommodation_id INT NOT NULL, slot_type VARCHAR(30) NOT NULL," +
    "slot_label VARCHAR(60) NOT NULL, stay_duration INT NOT NULL," +
    "check_in_date DATE NOT NULL, check_in_time TIME NOT NULL," +
    "check_out_date DATE NOT NULL, check_out_time TIME NOT NULL," +
    "item_price DECIMAL(12,2) NOT NULL," +
    "INDEX idx_acc (accommodation_id)," +
    "FOREIGN KEY (reservation_id) REFERENCES reservations(id)," +
    "FOREIGN KEY (accommodation_id) REFERENCES accommodations(id)) ENGINE=InnoDB"
  ];
  for (const sql of ddl) await pool.query(sql);

  await pool.query("INSERT INTO accommodation_categories VALUES (1, 'Room')");
  await pool.query("INSERT INTO accommodations " +
    "(id,category_id,name,status,day_price,overnight_price,extended_price) VALUES " +
    "(7,1,'Test Room 7','available',300,350,600)," +
    "(8,1,'Test Room 8','available',300,350,600)");
  for (const id of [17, 18, 19, 20, 21, 22]) {
    await pool.query("INSERT INTO reservations " +
      "(id,reservation_code,reservation_status,payment_status,is_checked_in," +
      "accommodation_total,required_downpayment,paid_amount,remaining_balance,note) " +
      "VALUES (?,?,'approved','partially_paid',1,1000,500,500,500,'Before add-on')",
      [id, "TEST-" + id]);
  }

  // The original handler executes against real MySQL through this isolated pool.
  replaceModule("../config/db", { promise() { return pool; } });
  const denyPayPal = () => { throw new Error("PayPal is forbidden in this test"); };
  replaceModule("../services/paypalService", {
    createPayPalOrder: denyPayPal,
    capturePayPalOrder: denyPayPal,
    getPayPalOrder: denyPayPal
  });
  addAccommodation = require("../controllers/shared/bookingController")
    .addAccommodationToReservation;
}

async function teardown() {
  try {
    if (pool) await pool.end();
  } finally {
    if (adminConnection) {
      try {
        if (schemaCreated) {
          // Drop ONLY the random test schema that this process just created.
          await adminConnection.query("DROP DATABASE " + schema);
        }
      } finally {
        await adminConnection.end();
      }
    }
  }
}

async function add(reservationId, accommodationId, date, slot = "day_tour") {
  const response = { status: null, body: null };
  const res = {
    status(code) { response.status = code; return this; },
    json(body) { response.body = body; return this; }
  };
  await addAccommodation({
    params: { id: String(reservationId) },
    body: {
      accommodation_id: accommodationId, check_in_date: date,
      slot_type: slot, stay_duration: 1
    }
  }, res);
  return response;
}

async function itemCount(accommodationId, date) {
  const [rows] = await pool.query(
    "SELECT COUNT(*) AS n FROM reservation_items WHERE accommodation_id=? " +
    "AND check_in_date=?", [accommodationId, date]);
  return Number(rows[0].n);
}

before(setup);
after(teardown);

test("Real InnoDB: two concurrent requests for SAME room have only one winner", async () => {
  const outcomes = await Promise.all([
    add(17, 7, "2099-03-01"), add(18, 7, "2099-03-01")
  ]);
  assert.deepEqual(outcomes.map((r) => r.status).sort((a,b)=>a-b), [201,409]);
  assert.equal(await itemCount(7, "2099-03-01"), 1);
  const [rows] = await pool.query(
    "SELECT accommodation_total, paid_amount, remaining_balance FROM " +
    "reservations WHERE id IN (17,18)");
  assert.deepEqual(rows.map((r)=>Number(r.accommodation_total)).sort((a,b)=>a-b),
    [1000,1300]);
  assert.deepEqual(rows.map((r)=>Number(r.paid_amount)), [500,500]);
  assert.deepEqual(rows.map((r)=>Number(r.remaining_balance)).sort((a,b)=>a-b),
    [500,800]);
});

test("Real InnoDB: different rooms accept two concurrent reservations", async () => {
  const results = await Promise.all([
    add(19, 7, "2099-03-05"), add(20, 8, "2099-03-05")
  ]);
  assert.deepEqual(results.map((r) => r.status), [201,201]);
  assert.equal(await itemCount(7, "2099-03-05"), 1);
  assert.equal(await itemCount(8, "2099-03-05"), 1);
});

test("Real InnoDB: day and night of same room can both book", async () => {
  const results = await Promise.all([
    add(21, 7, "2099-03-07", "day_tour"),
    add(22, 7, "2099-03-07", "night")
  ]);
  assert.deepEqual(results.map((r) => r.status), [201,201]);
  assert.equal(await itemCount(7, "2099-03-07"), 2);
});
